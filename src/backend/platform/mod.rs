#[cfg(all(unix, target_os = "linux"))]
mod pkexec;

/// Relaunch this executable with administrator rights and wait until the
/// elevated instance is actually running.
///
/// `args` must carry the handshake token generated by the caller (see
/// [`crate::backend::elevation`]); returning `Ok` means the elevated instance
/// has published its readiness marker, so the caller may release the
/// single-instance lock and exit.
pub async fn relaunch_self_elevated(args: &[String]) -> Result<(), ElevationError> {
    #[cfg(windows)]
    {
        let args = args.to_vec();
        // `ShellExecuteW` blocks on the UAC consent prompt: keep it off the
        // async worker threads.
        tokio::task::spawn_blocking(move || windows_impl::relaunch_self_elevated(&args))
            .await
            .map_err(|err| ElevationError::Io(err.to_string()))?
    }
    #[cfg(all(unix, target_os = "linux"))]
    {
        pkexec::relaunch_self_elevated(args).await
    }
    #[cfg(all(unix, not(target_os = "linux")))]
    {
        let _ = args;
        Err(ElevationError::Unsupported)
    }
}
