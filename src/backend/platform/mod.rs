use thiserror::Error;

#[derive(Debug, Error)]
pub enum ElevationError {
    #[error("elevation is not supported on this platform")]
    Unsupported,
    #[error("user dismissed the authorization prompt")]
    UserCancelled,
    /// No graphical polkit authentication agent (or no graphical session to
    /// draw one in), so no password dialog can ever appear.
    #[error("no graphical authentication agent is available")]
    NoAuthenticationAgent,
    /// `pkexec` is missing, not setuid root, or otherwise unusable.
    #[error("pkexec is unavailable: {0}")]
    PkexecUnavailable(String),
    /// The elevation helper never reported a running instance.
    #[error("timed out waiting for the elevated instance to start")]
    Timeout,
    #[error("io error during elevation: {0}")]
    Io(String),
    #[error("elevation failed: {0}")]
    Failed(String),
}

impl ElevationError {
    /// User-facing (zh-CN) explanation, shown by the web UI after
    /// "提权失败：". The `Display` impl stays in English for logs.
    pub fn user_message(&self) -> String {
        match self {
            Self::Unsupported => "当前平台不支持自动提权，请手动以管理员身份运行本程序".into(),
            Self::UserCancelled => "已取消授权".into(),
            Self::NoAuthenticationAgent => {
                "未找到图形授权代理，无法弹出授权窗口。请确认系统已安装并正在运行 polkit \
                 授权代理（统信 UOS / Deepin 下为 dde-polkit-agent），或从桌面会话启动本程序；\
                 也可以在终端中用 sudo 启动本程序。"
                    .into()
            }
            Self::PkexecUnavailable(reason) => format!(
                "无法通过 pkexec 提权（{reason}）。请安装 policykit-1 并确认 \
                 /usr/bin/pkexec 带有 setuid 位（ls -l /usr/bin/pkexec 应显示 rws），\
                 或在终端中用 sudo 启动本程序。"
            ),
            Self::Timeout => "等待系统授权超时，已取消本次提权，请重试".into(),
            Self::Io(err) => format!("提权过程中出现系统错误：{err}"),
            Self::Failed(detail) => detail.clone(),
        }
    }
}

#[derive(Debug, Error)]
pub enum WaitError {
    #[error("io error during wait: {0}")]
    Io(#[from] std::io::Error),
    #[error("timed out waiting for process exit")]
    Timeout,
}

#[derive(Debug, Error)]
pub enum SingleInstanceError {
    #[error("another instance is already running")]
    AlreadyRunning,
    #[error("io error acquiring single-instance lock: {0}")]
    Io(#[from] std::io::Error),
}

